package main

import (
	"fmt"
	"os"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

func main() {
	if unicode.Version != "15.0.0" {
		panic("regenerate with Go unicode 15.0.0; review data updates separately")
	}
	f, _ := os.Create("internal/matching/regex_unicode.mbt")
	defer f.Close()
	fmt.Fprintf(f, "// Generated by scripts/generate_regex_unicode.go using Go unicode %s.\n///|\nlet re2_unicode_ranges : Map[String, String] = {\n", unicode.Version)
	tables := map[string]*unicode.RangeTable{}
	for k, v := range unicode.Scripts {
		tables[k] = v
	}
	for k, v := range unicode.Categories {
		tables[k] = v
	}
	names := []string{}
	for k := range tables {
		names = append(names, k)
	}
	sort.Strings(names)
	for _, name := range names {
		t := tables[name]
		var b strings.Builder
		write := func(lo, hi, step uint32) {
			for x := lo; x <= hi; {
				end := x
				if step == 1 {
					end = hi
				}
				fmt.Fprintf(&b, "\\u{%x}", x)
				if end != x {
					fmt.Fprintf(&b, "-\\u{%x}", end)
				}
				if step == 1 {
					break
				}
				x += step
			}
		}
		for _, r := range t.R16 {
			write(uint32(r.Lo), uint32(r.Hi), uint32(r.Stride))
		}
		for _, r := range t.R32 {
			write(r.Lo, r.Hi, r.Stride)
		}
		fmt.Fprintf(f, "  %s: %s,\n", strconv.Quote(name), strconv.Quote(b.String()))
	}
	fmt.Fprintln(f, "}")
}
