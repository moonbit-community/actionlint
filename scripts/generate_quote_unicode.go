package main

import (
	"fmt"
	"os"
	"strconv"
	"unicode"
)

func main() {
	if unicode.Version != "15.0.0" {
		panic("requires Unicode 15.0.0")
	}
	f, err := os.Create("internal/model/quote_unicode.mbt")
	if err != nil {
		panic(err)
	}
	defer f.Close()
	os.Stdout = f
	fmt.Println("// Generated by scripts/generate_quote_unicode.go from Go Unicode 15.0.0.\n// Copyright 2009 The Go Authors. All rights reserved.\n// BSD-3-Clause license: see THIRD_PARTY_NOTICES.\n\n///|\nfn go_printable(n : Int) -> Bool {\n  n is (")
	start := -1
	for n := 0; n <= 0x110000; n++ {
		printable := n < 0x110000 && strconv.IsPrint(rune(n))
		if printable && start < 0 {
			start = n
		}
		if !printable && start >= 0 {
			fmt.Printf("    0x%x..=0x%x |\n", start, n-1)
			start = -1
		}
	}
	fmt.Println("    -1\n  )\n}")
}
